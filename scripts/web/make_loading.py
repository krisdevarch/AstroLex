"""Builds the web loading screen (WP-F.13c). Deterministic; run from anywhere:
    python3 scripts/web/make_loading.py
Reads game/art/backdrop/low_orbit.jpg and game/fonts/Fredoka.ttf, writes
  game/brand/splash.png   Godot boot splash (painting + veil + logo, no bar)
  game/web/shell.html     custom HTML shell (from scripts/web/shell.template.html), one file
Needs Pillow; fontTools + brotli subset the font to woff2 (else a system rounded font is used).
"""
import base64
import io
import pathlib

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
PAINTING = ROOT / "game/art/backdrop/low_orbit.jpg"
FONT = ROOT / "game/fonts/Fredoka.ttf"
TEMPLATE = ROOT / "scripts/web/shell.template.html"
SHELL = ROOT / "game/web/shell.html"
SPLASH = ROOT / "game/brand/splash.png"
GLYPHS = "AstroLexSTRO0123456789%"
CYAN = (79, 216, 235)
VEIL = [(0.0, (5, 8, 20, 0.40)), (0.5, (5, 8, 20, 0.58)), (1.0, (5, 8, 20, 0.80))]  # as in the shell CSS


def cover(img, w, h):
    s = max(w / img.width, h / img.height)
    img = img.resize((round(img.width * s), round(img.height * s)), Image.LANCZOS)
    left, top = (img.width - w) // 2, (img.height - h) // 2
    return img.crop((left, top, left + w, top + h))


def veil(img):
    w, h = img.size
    layer = Image.new("RGBA", (1, h))
    for y in range(h):
        f = y / (h - 1)
        for (a, ca), (b, cb) in zip(VEIL, VEIL[1:]):
            if a <= f <= b:
                k = (f - a) / (b - a)
                c = [ca[i] + (cb[i] - ca[i]) * k for i in range(4)]
                layer.putpixel((0, y), (round(c[0]), round(c[1]), round(c[2]), round(c[3] * 255)))
                break
    return Image.alpha_composite(img.convert("RGBA"), layer.resize((w, h)))


def font_b64():
    try:
        from fontTools import subset
        from fontTools.ttLib import TTFont
        from fontTools.varLib import instancer
    except ImportError:
        return ""
    f = TTFont(str(FONT))
    if "fvar" in f:
        f = instancer.instantiateVariableFont(f, {"wght": 600, "wdth": 100})
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []
    opts.name_IDs = []
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=GLYPHS)
    sub.subset(f)
    f.flavor = "woff2"
    buf = io.BytesIO()
    f.save(buf)
    return base64.b64encode(buf.getvalue()).decode()


def make_splash(art):
    w, h = 1080, 1920
    img = veil(cover(art, w, h))
    size = round(w * 0.17)
    font = ImageFont.truetype(str(FONT), size)
    try:
        font.set_variation_by_axes([600, 100])
    except Exception:
        pass
    text = "AstroLex"
    cx = w / 2
    asc, desc = font.getmetrics()
    y = h * 0.34 - (asc + desc - size) / 2  # CSS line-height:1 centres the content area in a 1em line box
    glow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(glow).text((cx, y), text, font=font, fill=CYAN + (255,), anchor="mt")
    for blur, alpha in ((size * 0.7, 0.35), (size * 0.3, 0.65), (size * 0.1, 0.95)):
        g = glow.filter(ImageFilter.GaussianBlur(blur))
        g.putalpha(g.getchannel("A").point(lambda v, a=alpha: round(v * a)))
        img = Image.alpha_composite(img, g)
    ImageDraw.Draw(img).text((cx, y), text, font=font, fill=(255, 255, 255, 255), anchor="mt")
    img.convert("RGB").save(SPLASH, optimize=True)


def main():
    art = Image.open(PAINTING).convert("RGB")
    buf = io.BytesIO()
    cover(art, 540, 960).save(buf, "JPEG", quality=70, optimize=True)
    bg_b64 = base64.b64encode(buf.getvalue()).decode()
    make_splash(art)
    fb = font_b64()
    html = TEMPLATE.read_text().replace("{{BG_B64}}", bg_b64).replace("{{FONT_B64}}", fb)
    SHELL.parent.mkdir(parents=True, exist_ok=True)
    SHELL.write_text("<!-- Generated by scripts/web/make_loading.py from scripts/web/shell.template.html; do not edit. -->\n" + html)
    print(f"background {len(buf.getvalue())/1024:.0f} KB, font {len(fb)*3//4/1024:.1f} KB, "
          f"shell {SHELL.stat().st_size/1024:.0f} KB, splash {SPLASH.stat().st_size/1024:.0f} KB")


if __name__ == "__main__":
    main()
